import assert from 'node:assert/strict';
import { movementPose, planMovement } from '../js/core/movement-plan.js';
const p = (scene, spot) => ({ scene, spot });
const spots = { 'T/A': {type:'idle',x:10,y:60,scale:50}, 'T/W': {type:'waypoint',x:30,y:70,scale:40}, 'T/X': {type:'transfer',x:50,y:30,scale:25}, 'R/E': {type:'transfer',x:80,y:90,scale:70}, 'R/B': {type:'idle',x:40,y:70,scale:60}, 'T/M': {type:'tofrom',x:60,y:15,scale:20} };
const world = { spot(scene, spot) { return spots[`${scene}/${spot}`] || null; } };
const route = [p('T','A'),p('T','W'),p('T','X'),p('R','E'),p('R','B')];
const move = {entityId:'npc',minute:100,from:p('T','A'),to:p('R','B'),route};
assert.equal(movementPose({x:0,y:0},{x:0,y:10}),'front');
assert.equal(movementPose({x:0,y:10},{x:0,y:0}),'back');
assert.equal(movementPose({x:0,y:0},{x:-10,y:0}),'left');
assert.equal(movementPose({x:0,y:0},{x:10,y:0}),'right');
assert.equal(movementPose({x:0,y:0},{x:10,y:-10}),'back-three-quarter-right');
assert.equal(movementPose({x:0,y:0},{x:0,y:0}),'stationary');
const tavern = planMovement({moves:[move],endMinute:100,scene:'T',world});
assert.equal(tavern.length,1); assert.equal(tavern[0].mode,'walk');
assert.deepEqual(tavern[0].actions.map(action => action.kind), ['walk', 'pause', 'fade-out']);
assert.equal(tavern[0].actions[0].legs.length, 2);
assert.equal('legs' in tavern[0], false);
assert.equal('arrivals' in tavern[0], false);
assert.equal('departures' in tavern[0], false);
assert.equal(tavern[0].actions[0].legs[0].smoothArrival, true);
assert.equal(tavern[0].actions[0].legs[1].smoothArrival, false);
const room = planMovement({moves:[move],endMinute:100,scene:'R',world});
assert.deepEqual(room[0].actions.map(action => action.kind), ['fade-in', 'pause', 'turn', 'walk']);
assert.equal(room[0].actions[3].legs.length, 1);
assert.equal(planMovement({moves:[move],endMinute:100,scene:'OTHER',world}).length,0);
const skipped = planMovement({moves:[move],endMinute:110,scene:'T',world});
assert.equal(skipped.length,0);
assert.equal(planMovement({moves:[move],endMinute:110,scene:'R',world}).length,0);
assert.ok(Object.isFrozen(tavern) && Object.isFrozen(tavern[0]) && Object.isFrozen(tavern[0].actions));
assert.equal(spots['T/M'].type,'tofrom'); // Presentation markers never join navigation route.
assert.throws(()=>planMovement({moves:[move],endMinute:99,scene:'T',world}));
assert.equal(planMovement({moves:[move,{...move,entityId:'other'}],endMinute:100,scene:'T',world}).length,2);
console.log('movement-plan: ok');
