import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { World } from '../js/core/world.js';
import { EntityRegistry } from '../js/core/entities.js';
import { scenePresence } from '../js/core/presence.js';
import { RIONNE, BARMAID } from '../js/content/data.js';
const data = JSON.parse(readFileSync(new URL('../world/world-stage.json', import.meta.url)));
const world = new World(data);
const entities = new EntityRegistry(world);
entities.register(RIONNE);
entities.register(BARMAID);
assert.equal(world.spot('BERKLITH_TAVERN', 'SPOT_05').x, 27);
assert.equal(world.spot('BERKLITH_TAVERN', 'MISSING'), null);
assert.deepEqual(scenePresence(world, entities, 'MISSING'), []);
assert.deepEqual(scenePresence(world, entities, 'RIONNES_ROOM').map(p => p.id), ['CHARACTER_01']);
const before = entities.snapshot();
const present = scenePresence(world, entities, 'BERKLITH_TAVERN');
assert.equal(present.length, 1);
assert.equal(present[0].assetFamily, 'barmaid');
assert.equal(present[0].spot.scale, 25.5);
present[0].spot.x = 999;
assert.equal(world.spot('BERKLITH_TAVERN', 'SPOT_05').x, 27);
assert.deepEqual(entities.snapshot(), before);
entities.moveTo('CHARACTER_01', { scene: 'BERKLITH_TAVERN', spot: 'SPOT_04' }, 1);
assert.deepEqual(scenePresence(world, entities, 'BERKLITH_TAVERN').map(p => p.id), ['CHARACTER_01','NPC_01']);
console.log('PASS: read-only world spots, scene presence, state changes, asset families');
