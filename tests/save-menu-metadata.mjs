import assert from 'node:assert/strict';
import { DimensionGear } from '../js/core/dimension-gear.js';
import { PlayerState } from '../js/core/player.js';
import { EntityRegistry } from '../js/core/entities.js';
import { SaveSystem } from '../js/core/save.js';
const world = {hasScene: id => ['A','B'].includes(id), has: loc => loc?.scene==='A' && loc.spot==='X'};
const memory=new Map();
globalThis.localStorage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v),removeItem:k=>memory.delete(k)};
const gear=new DimensionGear();
const player=new PlayerState({world,start:{scene:'A',discoveredScenes:['A']}});
const entities=new EntityRegistry(world);
const saves=new SaveSystem({gear,player,entities});
assert.equal(saves.inspectManual(1),null);
saves.saveManual(1);
const info=saves.inspectManual(1);
assert.equal(info.sceneId,'A');
assert.match(info.timeLabel,/Y1 · M01 · D01 · SAT · 06:55/);
player.moveToScene('B');
saves.loadManual(1);
assert.equal(player.sceneId,'A');
saves.save();assert.equal(saves.hasLegacySave(),true);
const raw=saves.slots.readManual(1);
saves.slots.writeManual(2,JSON.stringify({...JSON.parse(raw),player:{scene:'BAD',discoveredScenes:['BAD']}}));
assert.throws(()=>saves.inspectManual(2));
assert.equal(player.sceneId,'A');
console.log('PASS: save menu metadata, manual restoration, legacy visibility, invalid slot');
