import assert from 'node:assert/strict';
import { DimensionGear, clockFromEpochMinute, formatClock } from '../js/core/dimension-gear.js';
import { Simulation } from '../js/core/simulation.js';
import { EntityRegistry } from '../js/core/entities.js';
const world = { has: loc => loc && loc.scene === 'S' && ['A','B'].includes(loc.spot) };
const gear = new DimensionGear();
const entities = new EntityRegistry(world);
entities.register({ id:'a', name:'A', agendaId:'a', start:{location:{scene:'S',spot:'A'}, activity:'IDLE'} });
entities.register({ id:'b', name:'B', agendaId:'b', start:{location:{scene:'S',spot:'A'}, activity:'IDLE'} });
let fail = false;
const agendas = { resolve(id) {
    if (id === 'b' && fail) throw new Error('agenda failure');
    return { id:'work', activity:'WORK', destination:{scene:'S',spot:'B'} };
} };
const navigator = { navigate(id, destination, minute) {
    entities.moveTo(id, destination, minute);
    return { moved:true, route:[] };
} };
const sim = new Simulation({ gear, entities, agendas, navigator });
const initialMinute = gear.epochMinute;
const initialEntities = entities.snapshot();
fail = true;
assert.throws(() => sim.advance(5), /agenda failure/);
assert.equal(gear.epochMinute, initialMinute);
assert.deepEqual(entities.snapshot(), initialEntities);
assert.equal(sim.log.length, 0);
fail = false;
const change = sim.advance(5);
assert.equal(change.now.epochMinute, initialMinute + 5);
assert.equal(entities.get('a').state.location.spot, 'B');
const committed = entities.snapshot();
const committedLog = sim.log.length;
fail = true;
assert.throws(() => sim.advance(1), /agenda failure/);
assert.deepEqual(entities.snapshot(), committed);
assert.equal(sim.log.length, committedLog);
assert.equal(gear.epochMinute, initialMinute + 5);
assert.throws(() => sim.advance(-1));
assert.throws(() => sim.advance(Number.MAX_SAFE_INTEGER));
assert.equal(gear.epochMinute, initialMinute + 5);
assert.equal(formatClock(clockFromEpochMinute(gear.epochMinute)), gear.format());
console.log('PASS: simulation rollback, successful advancement, clock validation and formatting');
