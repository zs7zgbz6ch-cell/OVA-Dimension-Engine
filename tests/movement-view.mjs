import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { legDuration } from '../js/ui/movement-view.js';
import { ENTITY_MOVEMENT_SPRITES } from '../js/content/game.js';
assert.equal(legDuration({x:10,y:10},{x:10,y:10}),260);
assert.equal(legDuration({x:0,y:0},{x:100,y:100}),1700);
assert.ok(legDuration({x:0,y:0},{x:20,y:0}) > legDuration({x:0,y:0},{x:5,y:0}));
assert.ok(ENTITY_MOVEMENT_SPRITES.rionne.front);
assert.ok(ENTITY_MOVEMENT_SPRITES.rionne.back);
assert.ok(ENTITY_MOVEMENT_SPRITES.rionne['front-three-quarter-left']);
assert.ok(ENTITY_MOVEMENT_SPRITES.rionne['back-three-quarter-left']);
const main = readFileSync(new URL('../js/main.js', import.meta.url),'utf8');
assert.match(main, /movementView\.cancel\(\)/);
assert.match(main, /movementView\.play\(result\)/);
const view = readFileSync(new URL('../js/ui/movement-view.js', import.meta.url),'utf8');
assert.match(view, /Promise\.allSettled\(tasks\)/);
assert.match(view, /player\.setInteraction\('MOVEMENT'\)/);
assert.match(view, /animation\.cancel\(\)/);
